import { PrismaClient } from '@prisma/client';
const p = new PrismaClient();
const SITE='cmuazd8v900011kiu4bp2hsnf';
const v = await p.demoVariant.findMany({ where: { siteId: SITE }, select: { id: true, templateId: true, isPreferred: true, previewToken: true } });
console.log('variants:', JSON.stringify(v));
const svcs = await p.service.findMany({ where: { siteId: SITE }, select: { title: true, slug: true, sourceUrl: true, shortDescription: true } });
for (const s of svcs) console.log('SVC', s.title, '|', s.slug, '|', s.sourceUrl, '|', (s.shortDescription||'').slice(0,90));
const prj = await p.project.findMany({ where: { siteId: SITE }, select: { title: true, slug: true, category: true, sourceUrl: true } });
for (const x of prj) console.log('PRJ', x.title, '|', x.slug, '| cat:', x.category, '|', x.sourceUrl);
await p.$disconnect();
